#!/usr/bin/env node
/*
 * Builds the motion library and the effect variants' tables from their sources: motion.json (presets and palettes),
 * variants.json (each effect variant's params) and tokens/tokens.json (durations and easing). Writes the same data module
 * to every pack (presets.ts in React, Angular and React Native, bx-presets.js in the premium JET pack) and
 * styles/kinds/_fx.css: the preset keyframes and classes (bx-m-<phase>-<name>) and each variant's settings as --bx-fx-*
 * variables on `<css>.bx-v-<variant>`. `node tools/gen-motion.mjs --check` writes nothing and fails when an output is out of date.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));

const tokens = read('tokens/tokens.json').motion;
const ms = (t) => parseInt(t.$value, 10);
export const DURATION = { fast: ms(tokens['duration-fast']), base: ms(tokens['duration-base']), slow: ms(tokens['duration-slow']) };
// The spring curve is bx.css's --bx-ease-spring; React Native springs with Animated.spring instead.
export const EASING = { standard: tokens['ease-standard'].$value, exit: tokens['ease-exit'].$value, spring: 'cubic-bezier(0.34, 1.56, 0.64, 1)' };
const spec = read('motion.json');
const { $comment: _c, ...PRESETS } = spec.presets;
const { $comment: _p, ...PALETTES } = spec.palettes;

// The effects (a css root in variants.json): each variant's params, the default's being none
const FX = {};
const CSS_ROOT = {};
for (const [id, c] of Object.entries(read('variants.json').components)) {
  if (!c.css) { continue; }
  FX[id] = Object.fromEntries(c.variants.map((v) => [v.id, v.params || {}]));
  CSS_ROOT[id] = c.css;
}

/* ---------- CSS ---------- */

const px = (n) => (n ? `${n}px` : '0');
/** One neutral frame as CSS declarations; keys the preset uses elsewhere fall back to their identity. */
function frameCss(f, keys) {
  const out = [];
  if (keys.has('opacity')) { out.push(`opacity: ${f.opacity ?? 1}`); }
  if (keys.has('x') || keys.has('y') || keys.has('scale') || keys.has('rotate')) {
    const t = [];
    if (f.x || f.y) { t.push(`translate(${px(f.x)}, ${px(f.y)})`); }
    if (f.scale !== undefined) { t.push(`scale(${f.scale})`); }
    if (f.rotate) { t.push(`rotate(${f.rotate}deg)`); }
    out.push(`transform: ${t.length ? t.join(' ') : 'none'}`);
  }
  if (keys.has('blur')) { out.push(`filter: ${f.blur ? `blur(${f.blur}px)` : 'none'}`); }
  return out.join('; ');
}
const keysOf = (frames) => new Set(frames.flatMap((f) => Object.keys(f)));
const timing = (p) => `var(--bx-dur-${p.duration}) var(--bx-ease-${p.easing})`;
function stateCss(s) {
  const out = [];
  const t = [];
  if (s.y) { t.push(`translateY(${s.y}px)`); }
  if (s.scale) { t.push(`scale(${s.scale})`); }
  if (t.length) { out.push(`transform: ${t.join(' ')}`); }
  if (s.shadow) { out.push(`box-shadow: var(--bx-shadow-${s.shadow})`); }
  if (s.glow) { out.push('box-shadow: 0 0 0 4px color-mix(in srgb, var(--bx-brand) 18%, transparent), 0 8px 24px color-mix(in srgb, var(--bx-brand) 24%, transparent)'); }
  if (s.tint) { out.push('background-color: color-mix(in srgb, var(--bx-brand) 8%, var(--bx-surface))'); }
  if (s.border) { out.push('border-color: var(--bx-brand)'); }
  return out.join('; ');
}
const DIRECTION = { left: [-1, 0], right: [1, 0], up: [0, -1], down: [0, 1] };
function varsCss(p) {
  const out = [];
  if (p.speed !== undefined) { out.push(`--bx-fx-speed: ${p.speed}`); }
  if (p.intensity !== undefined) { out.push(`--bx-fx-intensity: ${p.intensity}`); }
  if (p.density !== undefined) { out.push(`--bx-fx-density: ${p.density}`); }
  if (p.sensitivity !== undefined) { out.push(`--bx-fx-sensitivity: ${p.sensitivity}`); }
  if (p.palette) {
    PALETTES[p.palette].forEach((role, i) => out.push(`--bx-fx-c${i + 1}: var(--bx-${role})`));
    out.push('--bx-fx-gradient: linear-gradient(135deg, var(--bx-fx-c1), var(--bx-fx-c2))');
  }
  // right and down run against a component's own way (a marquee runs left, letters float up)
  if (p.direction) { const [x, y] = DIRECTION[p.direction]; out.push(`--bx-fx-x: ${x}`, `--bx-fx-y: ${y}`, `--bx-fx-play: ${x + y > 0 ? 'reverse' : 'normal'}`); }
  if (p.effect) { out.push(`--bx-fx-effect: ${p.effect}`); }
  if (p.easing) { out.push(`--bx-fx-ease: ${p.easing === 'linear' ? 'linear' : `var(--bx-ease-${p.easing})`}`); }
  return out.join('; ');
}

const START = '/* The motion library (generated by tools/gen-motion.mjs from motion.json; do not edit between these lines): bx-m-<phase>-<name>. Enter and change play once when the class is set, exit plays while .is-leaving, hover and press hold their state. */';
const END = '/* End of the motion library */';

/** The motion library's block, kept in base.css with the other shared keyframes. */
function library() {
  const lines = [START];
  for (const phase of ['enter', 'change', 'exit']) {
    for (const [name, p] of Object.entries(PRESETS[phase])) {
      const keys = keysOf(p.frames);
      const step = 100 / (p.frames.length - 1);
      lines.push(`@keyframes bx-m-${phase}-${name} { ${p.frames.map((f, i) => `${Math.round(i * step * 100) / 100}% { ${frameCss(f, keys)}; }`).join(' ')} }`);
      lines.push(phase === 'exit' ? `.bx-m-exit-${name}.is-leaving { animation: bx-m-exit-${name} ${timing(p)} forwards; }`
        : `.bx-m-${phase}-${name} { animation: bx-m-${phase}-${name} ${timing(p)} both; }`);
    }
  }
  for (const phase of ['hover', 'press']) {
    for (const [name, p] of Object.entries(PRESETS[phase])) {
      const on = phase === 'hover' ? ':hover:not(:disabled):not(.is-disabled)' : ':active:not(:disabled):not(.is-disabled)';
      lines.push(`.bx-m-${phase}-${name} { transition: transform ${timing(p)}, box-shadow ${timing(p)}, background-color ${timing(p)}, border-color ${timing(p)}; }`);
      lines.push(`.bx-m-${phase}-${name}${on} { ${stateCss(p.state)}; }`);
    }
  }
  lines.push(END);
  return lines.join('\n') + '\n';
}

/** base.css with its motion library block written (appended the first time). */
function base() {
  const now = fs.readFileSync(path.join(root, 'styles/base.css'), 'utf8').replace(/\r\n/g, '\n');
  const at = now.indexOf(START);
  const end = now.indexOf(END);
  return at < 0 ? now + library() : now.slice(0, at) + library() + now.slice(end + END.length + 1);
}

function css() {
  const lines = ['/* Generated by tools/gen-motion.mjs from variants.json and motion.json. Do not edit; change those and run it. */',
    '/* Effect variants: each one\'s settings as --bx-fx-* variables on <root>.bx-v-<id>, read by its kind\'s styles. */'];
  for (const [id, variants] of Object.entries(FX)) {
    for (const [v, p] of Object.entries(variants)) {
      const decl = varsCss(p);
      if (decl) { lines.push(`${CSS_ROOT[id]}.bx-v-${v} { ${decl}; }`); }
    }
  }
  return lines.join('\n') + '\n';
}

/* ---------- data modules ---------- */

const data = () => ({ DURATION, EASING, PRESETS, PALETTES, FX });
const HEAD = '/* Generated by tools/gen-motion.mjs from motion.json, variants.json and tokens/tokens.json. Do not edit; change those and run it. */\n';
function ts() {
  const d = data();
  return HEAD + `export type Phase = 'enter' | 'hover' | 'press' | 'change' | 'exit';
export interface Frame { opacity?: number; x?: number; y?: number; scale?: number; blur?: number; rotate?: number }
export interface Preset { what: string; duration: 'fast' | 'base' | 'slow'; easing: 'standard' | 'exit' | 'spring'; frames?: Frame[]; state?: Record<string, number> }
export interface FxParams { speed?: number; intensity?: number; density?: number; sensitivity?: number; palette?: string; direction?: string; effect?: string; easing?: string }

export const DURATION = ${JSON.stringify(d.DURATION)} as const;
export const EASING = ${JSON.stringify(d.EASING)} as const;
export const PRESETS: Record<Phase, Record<string, Preset>> = ${JSON.stringify(d.PRESETS, null, 2)} as Record<Phase, Record<string, Preset>>;
export const PALETTES: Record<string, string[]> = ${JSON.stringify(d.PALETTES)};
export const FX: Record<string, Record<string, FxParams>> = ${JSON.stringify(d.FX, null, 2)};
`;
}
function amd() {
  const d = data();
  return HEAD + `define([], function () {
  'use strict';
  return ${JSON.stringify(d, null, 2).replace(/\n/g, '\n  ')};
});
`;
}

const outputs = {
  'styles/base.css': base(),
  'styles/kinds/_fx.css': css(),
  'react/src/presets.ts': ts(),
  'angular/src/presets.ts': ts(),
  'react-native/src/presets.ts': ts(),
  'jet-premium/bx/bx-presets.js': amd(),
  '../angular/starter/src/app/components/presets.ts': ts(),
};

const check = process.argv.includes('--check');
let stale = 0;
for (const [file, text] of Object.entries(outputs)) {
  const full = path.join(root, file);
  const now = fs.existsSync(full) ? fs.readFileSync(full, 'utf8').replace(/\r\n/g, '\n') : '';
  if (now === text) { continue; }
  if (check) { console.error(file + ' is out of date: run node target-packs/components/tools/gen-motion.mjs'); stale++; } else {
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, text);
    console.log('wrote ' + file);
  }
}
process.exit(stale ? 1 : 0);
