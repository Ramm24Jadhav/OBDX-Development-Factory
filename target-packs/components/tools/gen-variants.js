#!/usr/bin/env node
/*
 * Writes each pack's variant table from variants/*.json (one file per wave): for every component, its kind and the
 * variant ids it takes. The packs read the table to accept a variant property and add bx-<kind>--<variant>.
 *   node target-packs/components/tools/gen-variants.js           write the tables
 *   node target-packs/components/tools/gen-variants.js --check   exit 1 when a table is out of date
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'variants');
const HEAD = 'Generated by tools/gen-variants.js from variants/*.json; do not edit.';

function tables() {
  const byPack = { 'jet-premium': {}, react: {}, angular: {}, 'react-native': {} };
  fs.readdirSync(DIR).filter((f) => /^v\d+\.json$/.test(f)).sort().forEach((f) => {
    const wave = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8'));
    Object.keys(wave.components).sort().forEach((id) => {
      const c = wave.components[id];
      Object.keys(c.packs).forEach((p) => { if (c.packs[p].built) { byPack[p][c.packs[p].name] = [c.kind, c.variants]; } });
    });
  });
  return byPack;
}

function body(table) {
  return '{\n' + Object.keys(table).sort().map((k) => `  '${k}': ['${table[k][0]}', [${table[k][1].map((v) => `'${v}'`).join(', ')}]]`).join(',\n') + '\n}';
}

function files() {
  const t = tables();
  const ts = (pack, what) => `// ${HEAD}\n/** ${what}: its kind and the variant ids it takes. */\nexport const VARIANTS: Record<string, readonly [string, readonly string[]]> = ${body(t[pack])};\n`;
  return {
    'jet-premium/bx/bx-variants.js': `/* ${HEAD} Each element: its kind and the variant ids it takes. */\ndefine([], function () {\n  'use strict';\n  return ${body(t['jet-premium']).replace(/\n/g, '\n  ')};\n});\n`,
    'react/src/variants-table.ts': ts('react', 'Each component'),
    'angular/src/variants-table.ts': ts('angular', 'Each element'),
    'react-native/src/variants-table.ts': ts('react-native', 'Each component'),
  };
}

const check = process.argv.includes('--check');
let stale = 0;
Object.entries(files()).forEach(([rel, text]) => {
  const file = path.join(ROOT, rel);
  // a Windows checkout has CRLF line ends (.gitattributes)
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
  if (old === text) { return; }
  if (check) { stale += 1; console.error(`${rel} is out of date: run node target-packs/components/tools/gen-variants.js`); } else { fs.writeFileSync(file, text); console.log(`wrote ${rel}`); }
});
process.exit(stale ? 1 : 0);
